#!/bin/bash
# Keeps justinpurnell.com's showcase pages current.
#
# Regenerates every page whose source repository has new commits (`showcase sync`), rebuilds the
# site, and opens a pull request on a dated branch. It never pushes to main directly.
#
#   - Refreshes only, sync clean (exit 0, no page failed): the PR is merged, which publishes.
#   - Any NEW page (added by `discover`): the PR is left open and you are alerted with a dialog
#     whose button starts scripts/review-site.sh, which previews each new page locally and asks
#     you to approve or decline it. Nothing new goes live unseen.
#   - Any page failure: the PR is left open.
#
# Config (environment, all optional):
#   SITE_DIR       the website checkout           (default: ../justinpurnell.com beside this repo)
#   SHOWCASE_ENV   file holding ANTHROPIC_API_KEY (default: ~/.config/showcase/env, must be mode 600)
#   SHOWCASE_DRY   set to 1 to print the plan and stop before any API call
#
# Refuses to run on a dirty website tree rather than stashing it.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SITE_DIR="${SITE_DIR:-$(cd "$HERE/../.." && pwd)/justinpurnell.com}"
SHOWCASE_ENV="${SHOWCASE_ENV:-$HOME/.config/showcase/env}"
MANIFEST="$SITE_DIR/showcase-manifest.json"
LOCK="${TMPDIR:-/tmp}/showcase-sync.lock"
export PATH="/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin:$HOME/.swiftly/bin:$PATH"

say() { printf '%s %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"; }
die() { say "ERROR: $*"; notify "Showcase sync failed: $*"; exit 1; }
notify() { osascript -e "display notification \"$1\" with title \"Showcase sync\"" >/dev/null 2>&1 || true; }

mkdir "$LOCK" 2>/dev/null || { say "another sync is running ($LOCK); exiting"; exit 0; }
trap 'rmdir "$LOCK"' EXIT

[ -f "$MANIFEST" ] || die "no manifest at $MANIFEST"

if [ "${SHOWCASE_DRY:-0}" != "1" ]; then
  [ -f "$SHOWCASE_ENV" ] || die "no API key file at $SHOWCASE_ENV"
  [ "$(stat -f '%Lp' "$SHOWCASE_ENV")" = "600" ] || die "$SHOWCASE_ENV must be mode 600"
  # Read the one key rather than sourcing the file, so nothing else in it is executed.
  ANTHROPIC_API_KEY="$(sed -n 's/^ANTHROPIC_API_KEY=//p' "$SHOWCASE_ENV" | tail -1)"
  export ANTHROPIC_API_KEY
  [ -n "$ANTHROPIC_API_KEY" ] || die "ANTHROPIC_API_KEY is empty in $SHOWCASE_ENV"
fi

say "building showcase"
( cd "$HERE" && swift build -c release 2>&1 | tail -1 )
SHOWCASE="$HERE/.build/release/showcase"

cd "$SITE_DIR"
[ -z "$(git status --porcelain)" ] || die "website tree is dirty; commit or discard first (never stashed)"
git fetch -q origin
git checkout -q main
git merge -q --ff-only origin/main || die "main cannot fast-forward"

if [ "${SHOWCASE_DRY:-0}" = "1" ]; then
  "$SHOWCASE" discover --manifest "$MANIFEST"
  "$SHOWCASE" sync --manifest "$MANIFEST" --dry-run
  exit 0
fi

# Add new public repositories to the manifest (bounded per run). A failure here, such as gh being
# signed out, must not stop the existing pages from being kept current.
say "discovering new projects"
NEW_SLUGS=""
NEW_SLUGS="$("$SHOWCASE" discover --manifest "$MANIFEST" --add)" || say "discover failed; syncing the existing manifest"

SYNC_STATUS=0
"$SHOWCASE" sync --manifest "$MANIFEST" || SYNC_STATUS=$?

if [ -z "$(git status --porcelain Content/showcase .showcase-state.json showcase-manifest.json)" ]; then
  say "nothing changed"
  [ "$SYNC_STATUS" -eq 0 ] || die "sync reported failures and changed nothing"
  exit 0
fi

say "rebuilding site"
swift run IgniteStarter 2>&1 | tail -3

BRANCH="showcase/sync-$(date +%Y-%m-%d)"
git checkout -q -b "$BRANCH" 2>/dev/null || git checkout -q "$BRANCH"
git add Content/showcase .showcase-state.json showcase-manifest.json docs
git commit -q -m "chore(showcase): regenerate pages whose source moved" \
  -m "Generated by project-showcase scripts/sync-site.sh."
git push -q -u origin "$BRANCH"

BODY="Pages regenerated by \`showcase sync\` because their source repositories gained commits."
if [ -n "$NEW_SLUGS" ]; then
  BODY="$BODY

## New pages awaiting approval
"
  while IFS= read -r slug; do
    BODY="$BODY- \`$slug\`: https://www.justinpurnell.com/showcase/$slug/ (live after merge)
"
  done <<< "$NEW_SLUGS"
  BODY="$BODY
Preview and approve or decline each one with \`scripts/review-site.sh\` in project-showcase."
fi
gh pr create --base main --head "$BRANCH" --title "Showcase sync $(date +%Y-%m-%d)" --body "$BODY" \
  || say "PR already exists or could not be created"

git checkout -q main

if [ "$SYNC_STATUS" -ne 0 ]; then
  die "partial failure: some pages did not regenerate; PR left open for review"
fi

if [ -n "$NEW_SLUGS" ]; then
  COUNT="$(printf '%s\n' "$NEW_SLUGS" | wc -l | tr -d ' ')"
  LIST="$(printf '%s\n' "$NEW_SLUGS" | sed 's/^/ - /')"
  say "$COUNT new page(s) need approval; PR left open"
  # The dialog gives up after five minutes so an unattended Mac does not hold the lock for ever.
  ANSWER="$(osascript -e "button returned of (display dialog \"$COUNT new showcase page(s) need your approval:\n$LIST\" with title \"Showcase sync\" buttons {\"Later\", \"Review now\"} default button \"Review now\" giving up after 300)" 2>/dev/null)" || ANSWER=""
  if [ "$ANSWER" = "Review now" ]; then
    osascript -e "tell application \"Terminal\" to activate" \
              -e "tell application \"Terminal\" to do script \"'$HERE/scripts/review-site.sh'\"" >/dev/null 2>&1 \
      || say "could not open Terminal; run $HERE/scripts/review-site.sh"
  else
    notify "$COUNT new page(s) await approval: run scripts/review-site.sh"
  fi
  exit 0
fi

gh pr merge "$BRANCH" --merge --delete-branch || die "sync was clean but the PR could not be merged"
git pull -q --ff-only origin main
notify "Showcase sync merged and published ($BRANCH)"
